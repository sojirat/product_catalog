-- [5] Payment Method รวม CC + SOF
SELECT *
FROM (
    -- CC
    SELECT DISTINCT
        'CC'            AS PAYMENT_METHOD,
        NULL            AS PAYMENT_NAME,
        cm.BANK_ABBR,
        cm.BANK_NAME_ENG AS BANK_NAME,
        cm.CARD_TYPE,
        ipt.CARD_DIGITS,
        ipt.PREFIX
    FROM  CREDIT_CARD_MASTER cm
    LEFT JOIN INST_PARTNER ipt ON ipt.BANK_ABBR = cm.BANK_ABBR

    UNION ALL

    -- SOF Draft
    SELECT DISTINCT
        p.PAYMENT_METHOD,
        NULL            AS PAYMENT_NAME,
        p.BANK_ABBR,
        p.BANK_DESC_ENG AS BANK_NAME,
        c.CARD_TYPE,
        ipt.CARD_DIGITS,
        ipt.PREFIX
    FROM  TR_PAYMENT p
    LEFT JOIN CREDIT_CARD_MASTER c   ON c.BANK_ABBR   = p.BANK_ABBR
    LEFT JOIN INST_PARTNER       ipt ON ipt.BANK_ABBR = p.BANK_ABBR
    WHERE (p.TRADE_NO = 'TP26010155' AND p.TRADE_PRODUCT_ID IS NULL)
       OR  p.TRADE_PRODUCT_ID = 529347
) AS A
ORDER BY PAYMENT_METHOD, BANK_ABBR, CARD_TYPE;


-- [6] SOF Draft เฉพาะ TR_PAYMENT
SELECT DISTINCT
