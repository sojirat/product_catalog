    ipt.CARD_DIGITS,
    ipt.PREFIX
FROM  TR_PAYMENT p
LEFT JOIN CREDIT_CARD_MASTER c   ON c.BANK_ABBR   = p.BANK_ABBR
LEFT JOIN INST_PARTNER       ipt ON ipt.BANK_ABBR = p.BANK_ABBR
WHERE (p.TRADE_NO = 'TP26010155' AND p.TRADE_PRODUCT_ID IS NULL)
   OR  p.TRADE_PRODUCT_ID = 529347;


